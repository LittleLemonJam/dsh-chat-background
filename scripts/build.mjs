#!/usr/bin/env node
/**
 * Build the browser half: bundle `src/index.js` and every module it imports into
 * the single `client.js` file the DSH client module loader serves.
 *
 * The build is deterministic (no timestamps, no commit hash in the banner), so
 * `--check` can rebuild in memory and tell whether the committed artifact is
 * stale. React is NOT bundled: the factory receives the shell's `require` and
 * the binding takes React from there.
 *
 * Usage:
 *   node scripts/build.mjs           write client.js
 *   node scripts/build.mjs --check   fail when client.js differs from a rebuild
 */
import { build } from 'esbuild'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))
const OUTPUT = join(ROOT, 'client.js')
const CHECK_ONLY = new Set(process.argv.slice(2)).has('--check')

const banner = `/**
 * ${pkg.name} v${pkg.version}
 * ${pkg.description}
 * @author ${pkg.author}
 * @license ${pkg.license}
 * @homepage ${pkg.homepage}
 *
 * Generated by scripts/build.mjs from src/ — do not edit this file by hand.
 */`

const result = await build({
  entryPoints: [join(ROOT, 'src', 'index.js')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: ['es2022'],
  charset: 'utf8',
  legalComments: 'none',
  sourcemap: false,
  logLevel: 'warning',
  banner: { js: banner },
  define: {
    __PACKAGE_NAME__: JSON.stringify(pkg.name),
    __PACKAGE_VERSION__: JSON.stringify(pkg.version)
  }
})

const produced = result.outputFiles[0].text
const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : null

if (CHECK_ONLY) {
  if (current !== produced) {
    console.error('FAIL client.js is stale — run `npm run build` and commit the result')
    process.exit(1)
  }
  console.log('ok   client.js is up to date')
  process.exit(0)
}

writeFileSync(OUTPUT, produced, 'utf8')
console.log(`ok   built client.js (${Buffer.byteLength(produced)} bytes, ${pkg.name} v${pkg.version})`)
